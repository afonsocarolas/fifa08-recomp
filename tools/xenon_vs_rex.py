"""Differential test: XenonRecomp's and ReXGlue's C++ for the same guest instruction.

Finds instructions that the two recompilers translate differently, takes up to
N register-only instances of each (no memory access, calls or branches), and
writes a C++ program that runs both translations on the same random register
state and reports every mismatch.

Usage (from the repo root):
  py -I tools/xenon_vs_rex.py out-xvr.cpp [per_mnemonic]
Then build and run it with tools/xenon_vs_rex.cmd.
"""
import collections
import glob
import re
import sys

out_path = sys.argv[1]
per_mnemonic = int(sys.argv[2]) if len(sys.argv) > 2 else 6


def load(pattern, start_re):
    funcs = {}
    for f in glob.glob(pattern):
        s = open(f).read()
        for m in re.finditer(start_re, s):
            i = m.end()
            j = s.find('\n}\n', i)
            funcs[m.group(1)] = s[i:j]
    return funcs


def blocks(body):
    # [(comment, [code lines])], one per guest instruction.
    out = []
    cur = None
    for line in body.split('\n'):
        t = line.strip()
        if not t:
            continue
        if t.startswith('// '):
            cur = (t, [])
            out.append(cur)
        elif t.startswith('loc_') and t.endswith(':'):
            continue
        elif cur is not None:
            cur[1].append(t)
    return out


xen = load('xenon/ppc/ppc_recomp.*.cpp', r'PPC_FUNC_IMPL\(__imp__(sub_[0-9A-F]+)\) \{')
rex = load('game/generated/default/fifa08_recomp.*.cpp', r'DEFINE_REX_FUNC\((sub_[0-9A-F]+)\) \{')

# Anything touching memory, control flow, the host environment or traps.
skip = re.compile(r'LOAD|STORE|RAW_ADDR|goto|return|sub_|__imp__|CALL|trap|LOCK|TIMEBASE|'
                  r'Dbg_|switch|setjmp|longjmp|base \+|memset|__sync|atomic|REX_FATAL')

cases = collections.defaultdict(list)
for name in sorted(set(xen) & set(rex)):
    bx, br = blocks(xen[name]), blocks(rex[name])
    if len(bx) != len(br):
        continue
    for (cx, lx), (cr, lr) in zip(bx, br):
        if cx != cr:
            continue
        nx = [re.sub(r'\bPPC_', 'REX_', l) for l in lx]
        if nx == lr:
            continue
        code = ' '.join(nx + lr)
        if skip.search(code) or not lx or not lr:
            continue
        mn = cx[3:].split(' ')[0]
        if len(cases[mn]) < per_mnemonic:
            cases[mn].append((name, cx, nx, lr))

with open(out_path, 'w') as f:
    f.write('''// Generated by tools/xenon_vs_rex.py
#include <cstdio>
#include <cstring>
#include <cmath>
#include <climits>
#include <random>
#include <rex/ppc/context.h>
#include <rex/ppc/intrinsics.h>
using namespace rex::ppc;

#define CASE_LOCALS PPCRegister temp{}; PPCVRegister vTemp{}; uint32_t ea{}; (void)temp; (void)vTemp; (void)ea;
''')
    names = []
    for mn, items in sorted(cases.items()):
        for k, (fn, comment, xl, rl) in enumerate(items):
            ident = re.sub(r'\W', '_', mn) + f'_{k}'
            names.append((ident, mn, fn, comment))
            f.write(f'// {fn}: {comment}\n')
            f.write(f'static void x_{ident}(PPCContext& __restrict ctx, uint8_t* base) {{ CASE_LOCALS\n')
            for l in xl:
                f.write('\t' + l + '\n')
            f.write('}\n')
            f.write(f'static void r_{ident}(PPCContext& __restrict ctx, uint8_t* base) {{ CASE_LOCALS\n')
            for l in rl:
                f.write('\t' + l + '\n')
            f.write('}\n')
    f.write('''
struct Case { void (*x)(PPCContext&, uint8_t*); void (*r)(PPCContext&, uint8_t*); const char* mn; const char* where; };
static const Case kCases[] = {
''')
    for ident, mn, fn, comment in names:
        f.write(f'    {{x_{ident}, r_{ident}, "{mn}", "{fn}: {comment.replace(chr(34), "")}"}},\n')
    f.write('''};

// Random state: raw bits, or "nice" numbers (small ints, floats in +-8, the
// 3.0f+x form the D3D pack ops use) so float paths see realistic values.
static void Randomize(PPCContext& c, std::mt19937_64& rng, int mode) {
    auto* bytes = reinterpret_cast<uint8_t*>(&c);
    for (size_t i = 0; i < sizeof(c); i++) bytes[i] = uint8_t(rng());
    std::uniform_real_distribution<float> fd(-8.0f, 8.0f);
    std::uniform_int_distribution<int> small(-40, 40);
    for (auto* r : {&c.r0,&c.r1,&c.r2,&c.r3,&c.r4,&c.r5,&c.r6,&c.r7,&c.r8,&c.r9,&c.r10,&c.r11,&c.r12,&c.r13,&c.r14,&c.r15,
                    &c.r16,&c.r17,&c.r18,&c.r19,&c.r20,&c.r21,&c.r22,&c.r23,&c.r24,&c.r25,&c.r26,&c.r27,&c.r28,&c.r29,&c.r30,&c.r31})
        if (mode == 1) r->s64 = small(rng);
    for (int i = 0; i < 32; i++) {
        auto& fr = (&c.f0)[i];
        if (mode != 0) fr.f64 = fd(rng);
    }
    for (int i = 0; i < 128; i++) {
        auto& v = (&c.v0)[i];
        for (int e = 0; e < 4; e++) {
            if (mode == 1) v.f32[e] = fd(rng);
            else if (mode == 2) v.s32[e] = 0x40400000 + small(rng) * 97;
            else if (mode == 3) v.u32[e] = uint32_t(rng()) & 0x001F001F;
        }
    }
    c.fpscr.csr = 0x1F80;  // host MXCSR default; the ops set flush mode themselves
}

int main() {
    std::mt19937_64 rng(12345);
    static PPCContext a, b, start;
    int bad_cases = 0;
    for (const auto& k : kCases) {
        int fails = 0;
        for (int it = 0; it < 4000; it++) {
            Randomize(start, rng, it % 4);
            a = start; b = start;
            simde_mm_setcsr(0x1F80);
            k.x(a, nullptr);
            simde_mm_setcsr(0x1F80);
            k.r(b, nullptr);
            if (std::memcmp(&a, &b, sizeof(a)) != 0) {
                if (fails == 0) {
                    printf("MISMATCH %-12s %s\\n", k.mn, k.where);
                    const uint8_t* pa = reinterpret_cast<const uint8_t*>(&a);
                    const uint8_t* pb = reinterpret_cast<const uint8_t*>(&b);
                    const uint8_t* ps = reinterpret_cast<const uint8_t*>(&start);
                    for (size_t o = 0; o < sizeof(a); o += 16) {
                        if (std::memcmp(pa + o, pb + o, 16) == 0) continue;
                        printf("   +%04zX in  ", o); for (int j = 15; j >= 0; j--) printf("%02X", ps[o + j]);
                        printf("\\n         xen "); for (int j = 15; j >= 0; j--) printf("%02X", pa[o + j]);
                        printf("\\n         rex "); for (int j = 15; j >= 0; j--) printf("%02X", pb[o + j]);
                        printf("\\n");
                    }
                }
                fails++;
            }
        }
        if (fails) { bad_cases++; printf("   %d/4000 runs differ\\n", fails); }
    }
    printf("%zu cases, %d differ\\n", sizeof(kCases) / sizeof(kCases[0]), bad_cases);
}
''')
print(f'{sum(len(v) for v in cases.values())} cases over {len(cases)} mnemonics -> {out_path}')
